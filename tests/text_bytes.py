def canonical_text_bytes(data: bytes) -> bytes:
    """Return text bytes with platform-independent LF line endings."""
    return data.replace(b"\r\n", b"\n").replace(b"\r", b"\n")


def canonical_text_sha256(data: bytes) -> str:
    """Hash textual content after canonicalizing its line endings."""
    return hashlib.sha256(canonical_text_bytes(data)).hexdigest().upper()


def canonical_sha256_for_legacy_text_sha256(legacy_sha256: str) -> str:
    """Resolve an immutable raw-byte report hash to its canonical text hash."""
    try:
        return LEGACY_TEXT_SHA256_TO_CANONICAL[legacy_sha256.upper()]
    except KeyError as exc:
        raise AssertionError(
            f"unrecognized legacy textual SHA-256: {legacy_sha256}"
        ) from exc
